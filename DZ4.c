#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>

int main()
{
    setlocale(LC_ALL, "Rus");

    int A, B, C;
    int condition;

    // Сообщаем пользователю, что делает программа
    printf("=== КОНТРОЛЬ КАЧЕСТВА НА ФАБРИКЕ ИГРУШЕК ===\n");
    printf("Введите вес трех игрушек (A, B, C в граммах): ");

    // Считываем веса трех игрушек
    scanf("%d %d %d", &A, &B, &C);

    // Вычисляем логическое условие:
    // Партия принимается, если вес КАЖДОЙ из трех игрушек кратен 7.
    // Используем логическое И (&&), так как условие должно выполняться для всех трех.
    condition = (A % 7 == 0) && (B % 7 == 0) && (C % 7 == 0);

    // Выводим результат
    printf("Партия принята (1 - да, 0 - нет): %d\n", condition);

    return 0;
}